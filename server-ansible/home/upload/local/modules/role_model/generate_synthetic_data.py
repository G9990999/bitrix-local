def load_roles() -> list[dict]:
    roles = []
    with open(ROLES_CSV, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            roles.append(row)
    return roles


def main():
    all_roles = load_roles()
    all_role_names = [r["name"] for r in all_roles]

    training_data = []

    for role in all_roles:
        position = role["name"]
        profile = role["profile"]
        enabled = RULES.get(position, [position])
        permissions = {rn: (rn in enabled) for rn in all_role_names}
        training_data.append({
            "position": position,
            "profile": profile,
            "permissions": permissions,
        })

    for position, enabled in EXTRA_SAMPLES:
        permissions = {rn: (rn in enabled) for rn in all_role_names}
        training_data.append({
            "position": position,
            "profile": position,
            "permissions": permissions,
        })

    OUTPUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_JSON, "w", encoding="utf-8") as f:
        json.dump(training_data, f, ensure_ascii=False, indent=2)

    print(f"Generated {len(training_data)} training samples -> {OUTPUT_JSON}")


if __name__ == "__main__":
    main()